import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { lstat, mkdir, readFile, realpath, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { EXPLORE_VERSION, TOOL_ROOT } from "../shared/package-paths.js";

export const WORKFLOW_FILES = ["explore-review.yml", "explore-baseline.yml", "explore-compare.yml"] as const;
/** Installed by setup but not needed for pull request reviews: doctor reports one that is missing as a warning. */
export const OPTIONAL_WORKFLOW_FILES: ReadonlySet<string> = new Set(["explore-compare.yml"]);
/** Written by setup before npm distribution; CI now installs @expo/explore instead. */
export const LEGACY_VENDOR_DIRECTORY = ".github/vendor/expo-explore";
export const SECRET_ANCHOR = "# App-test secrets: one NAME: line per {{secret:NAME}} input in .expo-explore (expo-explore setup adds them).";

export type PackageManager = "npm" | "pnpm" | "yarn-classic" | "yarn" | "bun";

const VERSION_LINE = /^(\s+EXPLORE_VERSION:) .*$/m;
const FINGERPRINT_LINE = /^# Generated by expo-explore setup[^\n]*\n/m;
const EXACT_VERSION = /^[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?$/;

/** The @expo/explore version a workflow installs, if it names one. */
export function workflowVersion(workflow: string): string | undefined {
  return VERSION_LINE.exec(workflow)?.[0].split(":").slice(1).join(":").trim().replace(/^['"]|['"]$/g, "");
}

/** Point a workflow at this CLI's version. */
export function pinWorkflowVersion(workflow: string, version = EXPLORE_VERSION): string {
  return workflow.replace(VERSION_LINE, `$1 ${version}`);
}

function workflowBody(workflow: string): string {
  return workflow.replace(FINGERPRINT_LINE, "");
}

function bodyFingerprint(workflow: string): string {
  return createHash("sha256").update(workflowBody(workflow)).digest("hex").slice(0, 16);
}

/**
 * Record the rendered content in the first line so a later setup can tell a file it generated
 * from one the app edited: only an unmodified file is replaced when the template changes.
 */
export function stampWorkflow(workflow: string): string {
  return `# Generated by expo-explore setup. Edits are kept across upgrades; rerun setup --workflows --force to regenerate. Fingerprint: ${bodyFingerprint(workflow)}\n${workflowBody(workflow)}`;
}

/**
 * How an installed workflow differs from this version's template, once its version pin is set aside:
 * "stale" when setup generated it and nobody touched it (an older template), "edited" when it was
 * changed by hand too, undefined when it matches.
 */
export function workflowTemplateDrift(workflow: string, fresh: string): "stale" | "edited" | undefined {
  if (workflowBody(pinWorkflowVersion(workflow)) === workflowBody(fresh)) return undefined;
  return workflowUnmodified(workflow) ? "stale" : "edited";
}

export function workflowUnmodified(workflow: string): boolean {
  const recorded = /^# Generated by expo-explore setup.*Fingerprint: ([0-9a-f]{16})$/m.exec(workflow)?.[1];
  return recorded !== undefined && recorded === bodyFingerprint(workflow);
}

const TEMPLATE_INSTALL = /npm ci --ignore-scripts --prefix "([^"]+)"/g;
const INSTALL_STEP = /^(\s+)- name: Install app dependencies$/m;
/** The runners have Node and corepack but no bun, so a bun install needs this step first. */
const SETUP_BUN_STEP = "- uses: oven-sh/setup-bun@0c5077e51419868618aeaa5fe8019c62421857d6 # v2.2.0";

async function exists(path: string): Promise<boolean> {
  try { await lstat(path); return true; }
  catch (error) { if ((error as NodeJS.ErrnoException).code === "ENOENT") return false; throw error; }
}

function git(cwd: string, args: string[]): string | undefined {
  const result = spawnSync("git", ["-C", cwd, ...args], { encoding: "utf8", timeout: 10_000 });
  return result.error || result.status !== 0 ? undefined : result.stdout.trim();
}

/** The repository root holds the workflows; the app and its lockfile can sit below it. */
export async function ciLayout(project: string): Promise<{ root: string; projectDir: string; installDir: string; manager: PackageManager | undefined }> {
  const top = git(project, ["rev-parse", "--show-toplevel"]);
  if (!top) throw new Error("The app must be inside a Git repository. Run git init and commit the app, then rerun.");
  const root = await realpath(top);
  const app = await realpath(project);
  let installDir = app;
  let manager: PackageManager | undefined;
  for (;;) {
    manager = await packageManager(installDir);
    if (manager || installDir === root || !installDir.startsWith(`${root}/`)) break;
    installDir = dirname(installDir);
  }
  const path = (target: string) => relative(root, target) || ".";
  return { root, projectDir: path(app), installDir: manager ? path(installDir) : path(app), manager };
}

export async function packageManager(directory: string): Promise<PackageManager | undefined> {
  if (await exists(join(directory, "package-lock.json"))) return "npm";
  if (await exists(join(directory, "pnpm-lock.yaml"))) return "pnpm";
  if (await exists(join(directory, "bun.lock")) || await exists(join(directory, "bun.lockb"))) return "bun";
  if (await exists(join(directory, "yarn.lock"))) {
    return (await readFile(join(directory, "yarn.lock"), "utf8")).includes("# yarn lockfile v1") ? "yarn-classic" : "yarn";
  }
  return undefined;
}

/** A frozen-lockfile install without lifecycle scripts, as the npm template line does. */
export function installCommand(manager: PackageManager, directory: string): string {
  switch (manager) {
    case "npm": return `npm ci --ignore-scripts --prefix "${directory}"`;
    case "pnpm": return `corepack enable && pnpm install --frozen-lockfile --ignore-scripts --dir "${directory}"`;
    case "yarn-classic": return `corepack enable && (cd "${directory}" && yarn install --frozen-lockfile --ignore-scripts)`;
    case "yarn": return `corepack enable && (cd "${directory}" && yarn install --immutable --mode=skip-build)`;
    case "bun": return `(cd "${directory}" && bun install --frozen-lockfile --ignore-scripts)`;
  }
}

/** The names referenced as {{secret:NAME}}, already validated by the config reader. */
export function forwardedSecretNames(workflow: string): string[] {
  return [...workflow.matchAll(/^\s+([A-Za-z_][A-Za-z0-9_]*): \$\{\{ secrets\.\1 \}\}\s*$/gm)].map(match => match[1]!);
}

export function renderWorkflow(template: string, options: { projectDir: string; installDir: string; manager: PackageManager | undefined; secretNames: readonly string[] }): string {
  let text = pinWorkflowVersion(template)
    .replace(/^(\s+APP_PROJECT_DIR:) \.$/m, `$1 ${options.projectDir}`)
    .replace(/^(\s+APP_INSTALL_DIR:) \.$/m, `$1 ${options.installDir}`);
  if (options.manager && options.manager !== "npm") {
    text = text.replace(TEMPLATE_INSTALL, (_match, directory: string) => installCommand(options.manager!, directory));
  }
  if (options.manager === "bun") text = text.replace(INSTALL_STEP, (step, indent: string) => `${indent}${SETUP_BUN_STEP}\n${step}`);
  return stampWorkflow(addSecretLines(text, options.secretNames));
}

/** Insert `NAME: ${{ secrets.NAME }}` under each capture step's anchor, keeping existing lines. */
export function addSecretLines(workflow: string, names: readonly string[]): string {
  const present = new Set(forwardedSecretNames(workflow));
  const missing = [...new Set(names)].filter(name => !present.has(name)).sort();
  if (!missing.length) return workflow;
  return workflow.split("\n").flatMap(line => {
    if (line.trim() !== SECRET_ANCHOR) return [line];
    const indent = line.slice(0, line.length - line.trimStart().length);
    return [line, ...missing.map(name => `${indent}${name}: \${{ secrets.${name} }}`)];
  }).join("\n");
}

export type WorkflowIssue = { code: string; message: string; nextAction: string; file: string };

/** Problems that would stop an installed workflow before or during capture. */
export function workflowIssues(file: string, text: string, expected: { projectDir: string; installDir: string; manager: PackageManager | undefined; secretNames: readonly string[] }): WorkflowIssue[] {
  const issues: WorkflowIssue[] = [];
  if (text.includes("EXPLORE_TOOLS_COMMIT")) return [{ code: "WORKFLOW_OUTDATED", file,
    message: `${file} runs a vendored copy of Explore. CI now installs @expo/explore from npm.`,
    nextAction: `Delete ${file} and ${LEGACY_VENDOR_DIRECTORY}, rerun expo-explore setup --workflows, then delete the EXPLORE_TOOLS_COMMIT repository variable.` }];
  const version = workflowVersion(text);
  if (!version || !EXACT_VERSION.test(version)) issues.push({ code: "EXPLORE_VERSION_INVALID", file,
    message: `${file} does not pin an exact @expo/explore version (EXPLORE_VERSION is ${version ?? "missing"}).`,
    nextAction: "Run expo-explore setup --workflows to set it." });
  const value = (name: string) => new RegExp(`^\\s+${name}: (.+)$`, "m").exec(text)?.[1]?.trim().replace(/^['"]|['"]$/g, "");
  for (const [name, wanted] of [["APP_PROJECT_DIR", expected.projectDir], ["APP_INSTALL_DIR", expected.installDir]] as const) {
    const actual = value(name);
    if (actual !== wanted) issues.push({ code: "WORKFLOW_APP_DIR_MISMATCH", file,
      message: `${name} is ${actual ?? "missing"}, but the app layout needs ${wanted}.`,
      nextAction: `Set ${name}: ${wanted} in ${file}.` });
  }
  if (expected.manager && expected.manager !== "npm" && /npm ci --ignore-scripts --prefix/.test(text)) {
    const command = installCommand(expected.manager, "<dir>");
    issues.push({ code: "WORKFLOW_INSTALL_MISMATCH", file,
      message: `The app uses ${expected.manager.replace("-classic", "")}, but ${file} installs it with npm ci.`,
      nextAction: `Replace each npm ci --ignore-scripts --prefix "<dir>" line with: ${command}`
        + (expected.manager === "bun" ? `, and add a step before it: ${SETUP_BUN_STEP}` : "") });
  } else if (expected.manager === "bun" && !text.includes("oven-sh/setup-bun@")) {
    issues.push({ code: "WORKFLOW_INSTALL_MISMATCH", file,
      message: `${file} installs the app with bun, but no step sets up bun. The runner does not have it.`,
      nextAction: `Add a step before Install app dependencies: ${SETUP_BUN_STEP}` });
  }
  const forwarded = new Set(forwardedSecretNames(text));
  const missing = expected.secretNames.filter(name => !forwarded.has(name));
  if (missing.length) issues.push({ code: "EXPLORATION_SECRET_MISSING", file,
    message: `${file} does not pass ${missing.join(", ")} to capture.`,
    nextAction: `Add ${missing.map(name => `${name}: \${{ secrets.${name} }}`).join(", ")} to the env of the capture step (below the app-test secrets comment), or rerun expo-explore setup --workflows.` });
  return issues;
}

export type CiInstallResult = { written: string[]; kept: string[]; notes: string[] };

/**
 * Install both workflows, pinned to this CLI's version. A workflow setup generated and nobody
 * edited is regenerated from the current template; an edited one keeps its edits and only gets
 * its version and missing secret lines updated, unless `force` replaces it.
 */
export async function installCiFiles(project: string, secretNames: readonly string[], options: { force?: boolean } = {}): Promise<CiInstallResult> {
  const layout = await ciLayout(project);
  const result: CiInstallResult = { written: [], kept: [], notes: [] };
  await mkdir(join(layout.root, ".github/workflows"), { recursive: true });
  for (const name of WORKFLOW_FILES) {
    const path = join(layout.root, ".github/workflows", name);
    const relativePath = `.github/workflows/${name}`;
    const template = await readFile(join(TOOL_ROOT, "templates", name), "utf8");
    const fresh = renderWorkflow(template, { ...layout, secretNames });
    if (await exists(path)) {
      const current = await readFile(path, "utf8");
      if (current.includes("EXPLORE_TOOLS_COMMIT") && !options.force) {
        result.kept.push(relativePath);
        result.notes.push(`${relativePath} runs a vendored copy of Explore. Delete it and ${LEGACY_VENDOR_DIRECTORY}, then rerun expo-explore setup --workflows.`);
        continue;
      }
      const pinned = pinWorkflowVersion(current);
      const updated = addSecretLines(pinned, secretNames);
      if (options.force || workflowUnmodified(current)) {
        if (fresh !== current) {
          await writeFile(path, fresh);
          const reasons = [pinned !== current ? `@expo/explore ${EXPLORE_VERSION}` : "", updated !== pinned ? "secret lines" : "", workflowBody(updated) !== workflowBody(fresh) ? `regenerated from the @expo/explore ${EXPLORE_VERSION} template` : ""].filter(Boolean);
          result.written.push(`${relativePath} (${reasons.join(", ")})`);
        } else result.kept.push(relativePath);
        continue;
      }
      if (updated !== current) {
        await writeFile(path, updated);
        result.written.push(`${relativePath} (${[pinned !== current ? `@expo/explore ${EXPLORE_VERSION}` : "", updated !== pinned ? "secret lines" : ""].filter(Boolean).join(", ")})`);
      } else result.kept.push(relativePath);
      if (!current.includes(SECRET_ANCHOR) && secretNames.some(secret => !forwardedSecretNames(current).includes(secret))) {
        result.notes.push(`${relativePath} predates the app-test secrets comment; add the secret lines to its capture step by hand.`);
      }
      if (workflowBody(updated) !== workflowBody(fresh)) {
        result.notes.push(`${relativePath} ${FINGERPRINT_LINE.test(current) ? "was edited after setup generated it" : "predates generated-workflow fingerprints"}, so setup kept its contents; the @expo/explore ${EXPLORE_VERSION} template differs. Rerun expo-explore setup --workflows --force to replace it with the template.`);
      }
      continue;
    }
    await writeFile(path, fresh, { flag: "wx" });
    result.written.push(relativePath);
  }
  if (!layout.manager) result.notes.push("No lockfile was found for the app; CI installs need one (commit package-lock.json or your package manager's lockfile).");
  return result;
}
