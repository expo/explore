import { cp, mkdir, mkdtemp, readFile, rename, rm, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { basename, dirname, join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import {
  assertSameViewerBundle,
  inspectViewerBundle,
  isPathInside,
} from "./viewer-bundle.mjs";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const defaultRepositoryRoot = resolve(scriptDirectory, "../..");

export async function stageViewer(repositoryRoot = defaultRepositoryRoot, runCommand = spawnSync) {
  const hostRoot = join(repositoryRoot, "viewer-host");
  const publicRoot = join(hostRoot, "public");
  const target = join(publicRoot, "viewer");

  if (
    basename(hostRoot) !== "viewer-host"
    || basename(target) !== "viewer"
    || !isPathInside(hostRoot, target)
    || resolve(dirname(target)) !== resolve(publicRoot)
  ) throw new Error(`Refusing to stage into unexpected path: ${target}`);

  const npm = process.platform === "win32" ? "npm.cmd" : "npm";
  function runRoot(args, label) {
    const result = runCommand(
      npm,
      args,
      { cwd: repositoryRoot, env: process.env, stdio: "inherit" },
    );
    if (result.error) throw result.error;
    if (result.status !== 0) throw new Error(`${label} failed with status ${result.status}`);
  }

  runRoot(["exec", "--", "tsc", "-p", "viewer/tsconfig.json", "--noEmit"], "Root Viewer typecheck");
  // The local CLI serves dist/viewer at /. Hosting needs /viewer/, so sharing that
  // output directory would replace the local bundle while tests or servers use it.
  const buildRoot = await mkdtemp(join(tmpdir(), "expo-explore-host-viewer-"));
  try {
    const source = join(buildRoot, "viewer");
    runRoot(["run", "build:viewer", "--", "--base", "/viewer/", "--outDir", source], "Hosted Viewer build");

    const built = await inspectViewerBundle(source, "Fresh isolated Viewer build");
    await mkdir(publicRoot, { recursive: true });
    const temporaryRoot = await mkdtemp(join(publicRoot, ".viewer-stage-"));
    const temporaryBundle = join(temporaryRoot, "viewer");
    try {
      await cp(source, temporaryBundle, { recursive: true, force: false, errorOnExist: true });
      const staged = await inspectViewerBundle(temporaryBundle, "Temporary staged Viewer");
      assertSameViewerBundle(built, staged);
      await rm(target, { recursive: true, force: true });
      await rename(temporaryBundle, target);
    } finally {
      await rm(temporaryRoot, { recursive: true, force: true });
    }

    const installed = await inspectViewerBundle(target, "Installed staged Viewer");
    assertSameViewerBundle(built, installed);
    const generatedRoot = join(hostRoot, "src", "generated");
    await mkdir(generatedRoot, { recursive: true });
    const indexHtml = await readFile(join(target, "index.html"), "utf8");
    await writeFile(join(generatedRoot, "viewer-entry.js"),
      `// Generated by stage:viewer. Do not edit.\nexport const viewerIndexHtml = ${JSON.stringify(indexHtml)};\n`, "utf8");
    return installed;
  } finally {
    await rm(buildRoot, { recursive: true, force: true });
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const installed = await stageViewer();
  process.stdout.write(
    `Staged ${installed.files.length} Viewer files (${installed.totalBytes} bytes, ${installed.digest})\n`,
  );
}
